import Foundation

/// 用户主动点母鸡进来时，她先说的那一句。
///
/// 刻意**不走 AI**：这句话没有任何需要理解的东西，为它发一次网络请求
/// 既慢又费钱，还会让「点进去等一会儿才有反应」。本地随机取一句，
/// 界面一出现就有人在等你，这个「即时」本身就是体验的一部分。
///
/// 文案铁律和主动关心一脉相承：**不提问**。
/// 一进来就问「今天过得怎么样？」是打扰，是把开口的压力推给用户；
/// 她只是在那儿，你想说再说。
enum HenGreeting {

    private static let lines = [
        "咕……你来啦",
        "咕咕，看起来你都不想我..",
        "咕咕 你想起我了诶",
        "咕——我刚在发呆",
        "咕咕咕我好想你",
        "咕咕咕，想你",
    ]

    static func random() -> String {
        lines.randomElement() ?? "咕……你来啦"
    }
}
