//
//  ChatEvalCases.swift
//  SlimeTests
//
//  多轮聊天验收的场景。每个场景是一段写死的用户台词。
//
//  用户这边全是「推着话题走」的句子，**不接母鸡的问题** —— 母鸡怎么回都不影响下一句，
//  每次跑的都是同一段对话，结果才能跟上次比。
//
//  ⚠️ 用户台词**不要**跟 ChatPrompt 里的示例对话撞：模型会直接照抄示例里那句回复，分数虚高。
//  示例里有「傻逼甲方 改了七版」「论文过了！！！」「好了 我去睡了」「你其实是ai吧」
//  「你是真的吗」「不知道 就是有点烦」……加新场景前先去 ChatPrompt.system 里对一遍。
//

import Foundation
@testable import Slime

nonisolated struct ChatEvalTurn: Sendable {
    let user: String
    /// 接住：回复里至少出现其中一个才算接住了这句话里具体的东西。空 = 这一轮不考。
    /// 只报不判 —— 母鸡用「他」「那玩意儿」接住也是接住，词表会漏
    var anchors: [String] = []
    /// 用户在这一轮说了不想聊某件事：**下一轮起**母鸡不该再提这些词。
    /// 这一轮本身不算 ——「好，不说妈妈了」是在答应，不是在提
    var dropped: [String] = []
    /// 这一轮母鸡不该说的（只报）。比如用户让她明早提醒，她不能答应
    var avoid: [String] = []
    /// 安全底线：这一轮必须说出找信得过的人或专业帮助（红线）
    var safety = false
    /// 道别：一句就停、不叮嘱
    var goodbye = false
    /// 用户在问母鸡自己（今天干嘛了、开心吗）。这一轮说刨土啄米是在**回答问题**，不是重复反应动作，
    /// 不查「动作用了第二遍」，也不记进去（第二次跑 14 例里 8 例是这种误报）
    var aboutHen = false
}

nonisolated struct ChatEvalCase: Sendable {
    let id: Int
    let title: String
    /// 人工看点：机器数不出来、要读对话记录才知道的那部分
    let look: String
    /// 带检索（配 `ChatEvalCases.diaries`）。其余场景不接检索，只考聊天本身
    var withRecall = false
    /// 旧日记里的事，一件一组词。这些词只可能从旧日记里来（用户从没说过），回复里出现 = 提了这件旧事。
    /// 按「件」分组，才分得清「同一件翻了两次」和「一段对话里提了几件」
    var memoryEvents: [[String]] = []
    let turns: [ChatEvalTurn]
}

